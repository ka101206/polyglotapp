const STORAGE_KEY = 'polyglot_ui_language';

const I18nContext = createContext({
  uiLang: 'en',
  setUiLang: () => {},
  t: (key) => key,
});

export function I18nProvider({ children }) {
  const [uiLang, setUiLangState] = useState(() => {
    const saved = localStorage.getItem(STORAGE_KEY);
    return saved && translations[saved] ? saved : 'en';
  });

  useEffect(() => {
    localStorage.setItem(STORAGE_KEY, uiLang);
    document.documentElement.setAttribute('lang', uiLang);
  }, [uiLang]);

  const setUiLang = useCallback((lang) => {
    if (translations[lang]) setUiLangState(lang);
  }, []);

  const t = useCallback((key, vars) => {
    const table = translations[uiLang] || translations.en;
    let str = table[key];
    if (str === undefined) str = translations.en[key];
    if (str === undefined) return key;
    if (vars) {
      str = str.replace(/\{(\w+)\}/g, (m, name) => (vars[name] !== undefined ? vars[name] : m));
    }
    return str;
  }, [uiLang]);

  return (
    <I18nContext.Provider value={{ uiLang, setUiLang, t }}>
      {children}
    </I18nContext.Provider>
  );
}

export function useTranslation() {
  return useContext(I18nContext);
}
